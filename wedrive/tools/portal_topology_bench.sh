#!/usr/bin/env bash
# Композит против МОНОЛИТА: Молдова и Румыния, собранные одним проходом, — эталон.
#
# Три колонки на каждый маршрут:
#   монолит          когерентная сборка обеих стран (715 тайлов, 491 МБ, 2 мин 18 с)
#   зона перекрытия  12508 порталов: все совпадающие узлы у границы
#   погранпереходы   32 записи: только рёбра, реально пересекающие государственную границу
#
# Погранпереходы находятся ИЗ ДАННЫХ: каждый граф несёт admin-информацию только своей страны,
# поэтому ребро «своя страна -> страна не определена» буквально пересекает границу.
set -u
L="docker exec vhdev /tmp/loki_route"
MD=${MD:-/regions/moldova/tiles}
RO=${RO:-/regions/romania/tiles}
MONO=${MONO:-/regions/mono/tiles}

one() { # dirA dirB lat lon lat lon table label
  local out km sec sw t0 t1 ms
  t0=$(date +%s%N)
  if [ -n "$7" ]; then
    out=$($L "$1" "$2" $3 $4 $5 $6 "$7" 2>&1)
  else
    out=$($L "$1" "$2" $3 $4 $5 $6 2>&1)
  fi
  t1=$(date +%s%N); ms=$(( (t1 - t0) / 1000000 ))
  km=$(echo "$out" | grep -oP 'МАРШРУТ НАЙДЕН\s+\K[0-9.]+' || true)
  sec=$(echo "$out" | grep -oP 'км\s+\K[0-9.]+' || true)
  sw=$(echo "$out" | grep -oP 'смен региона \K[0-9]+' || true)
  if [ -z "$km" ]; then
    printf '   %-18s  %s\n' "$8" "NO ROUTE"
  else
    printf '   %-18s %9s км %9s с  смен %3s  %5s мс\n' "$8" "$km" "$sec" "$sw" "$ms"
  fi
}

route() { # lat lon lat lon name
  echo "=== $5"
  one "$MONO" "$MONO" "$1" "$2" "$3" "$4" ""                       "монолит"
  one "$MD"   "$RO"   "$1" "$2" "$3" "$4" /tmp/portals_all.txt      "зона перекрытия"
  one "$MD"   "$RO"   "$1" "$2" "$3" "$4" /tmp/portals_border.txt   "погранпереходы"
}

