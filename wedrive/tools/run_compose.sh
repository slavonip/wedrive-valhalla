#!/usr/bin/env bash
# Собрать стенд составного графа и прогнать четыре случая одним заходом.
#
# Одним заходом — это и есть смысл: отрицательные контроли и положительный результат должны
# выйти из ОДНОГО бинарника и ОДНОЙ сборки. Иначе «в одном графе маршрута нет, а в составном
# есть» перестаёт быть доказательством: разница могла приехать из пересборки между запусками.
#
# Четыре случая на одной паре точек:
#   md          только Молдова   — обязан ответить NO ROUTE
#   ro          только Румыния   — обязан ответить NO ROUTE
#   both        оба графа, без таблицы порталов — тоже NO ROUTE, и это главный контроль:
#               доказывает, что дело в ПОРТАЛЕ, а не в том, что просто добавили второй граф
#   both+portal оба графа и таблица — маршрут есть
#
#   usage: run_compose.sh [каталог-MD] [каталог-RO] [таблица-порталов]
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MD="${1:-/regions/moldova_bc/tiles}"
RO="${2:-/regions/romania_bc/tiles}"
PORTALS="${3:-/regions/portals_bc.txt}"

# Исходник берётся ИЗ РЕПОЗИТОРИЯ, рядом с этим скриптом. В прежней версии здесь стоял
# абсолютный путь к каталогу конкретной сессии — вне её скрипт молча собирал не то или не
# собирал ничего.
sed 's/\r$//' "$HERE/compose_route.cc" > /tmp/compose_route.cc
docker cp /tmp/compose_route.cc vhdev:/tmp/ >/dev/null

echo "########## сборка"
# Без `| head`: обрыв пайпа шлёт g++ SIGPIPE, и сборка выглядит упавшей, хотя дело в тесте.
docker exec vhdev bash -c 'cd /tmp && g++ -std=c++20 -O2 compose_route.cc -o compose_route \
  $(pkg-config --cflags --libs libvalhalla) 2>&1 | grep -E "error:" | head -20'
docker exec vhdev test -x /tmp/compose_route || { echo "СБОРКА НЕ УДАЛАСЬ"; exit 1; }
echo "   ok"

# Кишинёв -> Хуши. Кишинёв существует только в Молдове, Хуши — только в Румынии: ближайший
# молдавский узел там в 8.8 км, далеко за любым радиусом привязки. Поэтому ни один граф в
# одиночку ответить не может, и это свойство пары, а не совпадение.
O="47.0105 28.8638"
D="46.6750 28.0600"

for mode in md ro both both+portal; do
  echo
  echo "########## Кишинёв -> Хуши   [$mode]"
  docker exec vhdev /tmp/compose_route "$MD" "$RO" $O $D "$mode" "$PORTALS"
done
