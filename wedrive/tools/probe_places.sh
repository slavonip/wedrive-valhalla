#!/usr/bin/env bash
# Насколько далеко экстракт заходит за собственную границу.
#
# От этого зависит, честен ли кросс-региональный тест. Если граф Молдовы уже содержит Яссы, то
# маршрут туда не доказывает НИЧЕГО о порталах: обе точки лежат в одном графе, и переход просто
# не понадобится. Поэтому прежде чем объявлять маршрут доказательством, надо знать, где
# заканчивается каждый экстракт.
#
# Тот же вопрос всплыл с другой стороны позже и остался открытым: однопроходная сборка над двумя
# экстрактами Geofabrik выдаёт на границе 33 подряд «Keep ... to stay on M1/E 581» на 2.4 км, и
# правдоподобное объяснение — что перекрывающаяся полоса импортируется дважды. Проба в одной
# точке дубликатов не нашла, механизм не доказан (см. MULTI-REGION.md). Этот инструмент меряет
# ровно ту величину, от которой ответ зависит.
#
#   usage: probe_places.sh [каталог-A] [каталог-B]
set -u
A="${1:-/regions/moldova_bc/tiles}"
B="${2:-/regions/romania_bc/tiles}"

docker exec vhdev test -x /tmp/portal_probe 2>/dev/null || {
  echo "нет /tmp/portal_probe — соберите wedrive/tools/portal_probe.cc" >&2; exit 2; }

probe() {
  echo "##### $3   ($1, $2)"
  docker exec vhdev /tmp/portal_probe "$A" "$B" "$1" "$2" 2>/dev/null \
    | grep -E "^(MOLDOVA|ROMANIA)|nothing within|^   node" | head -4
  echo
}

# Точки подобраны по РАССТОЯНИЮ ОТ ГРАНИЦЫ, а не по известности: важно, где именно обрывается
# каждый граф, а не как называется место.
probe 47.1585 27.6014 "Яссы, 60 км вглубь Румынии"
probe 46.6700 28.0600 "Хуши, 20 км вглубь Румынии"
probe 46.8233 28.1407 "сам переход"
probe 47.0105 28.8638 "Кишинёв"
probe 44.4268 26.1025 "Бухарест"
